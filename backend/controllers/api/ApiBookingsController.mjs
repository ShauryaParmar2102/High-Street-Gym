import express from "express";
import { ApiAuthenticationController } from "./ApiAuthenticationController.mjs";
import { BookingModel } from "../../models/BookingModel.mjs";
import { DatabaseModel } from "../../models/DatabaseModel.mjs";
import { SessionActivityModel } from "../../models/SessionActivityModel.mjs";

export class ApiBookingsController{
    static routes = express.Router();

    static {
    // Run authentication middleware for API requests
    this.routes.use(ApiAuthenticationController.middleware);

    // Allow access only to authenticated users
    this.routes.use(ApiAuthenticationController.restrict("any"));

    // Booking routes
    this.routes.post("/", this.createBooking);   // Create a new booking
    this.routes.get("/", this.getUserBookings); // Retrieve bookings for the logged-in user
    this.routes.get("/xml", this.getMemberBookingsXML); // Export the logged-in user's bookings as XML
    this.routes.delete("/:id", this.deleteBooking); // Delete a booking by ID
}

// Create a new booking for the logged-in user
    static async createBooking(req, res) {
        try {
            const booking = new BookingModel(
            null,  // Booking ID is generated by the database
            req.authenticatedUser.id, // ID of the logged-in user
            req.body.sessionId, // ID of the session being booked
            "booked", // Initial booking status
            new Date(), // Date and time the booking was created
        );

            const result = await BookingModel.create(booking); // Save the new booking to the database

            return res.status(200).json({
    id: result.insertId,
    message: "Booking created successfully",
});

} catch (error) {
    console.log(error);

    // Check if the member has already booked this session
    if (error.code === "ER_DUP_ENTRY") {
        return res.status(409).json({
            message: "You have already booked this session."
        });
    }

    // Handle other errors when creating a booking
    return res.status(500).json({
        message: "Unable to book this session. Please try again later.",
        errors: [error.message || error],
    });
}
}

    //Get bookings for a User that is logged in
    static async getUserBookings(req,res) {
        try {
            const bookings = await BookingModel.getByMemberId(req.authenticatedUser.id);

            return res.status(200).json(bookings);
        } catch(error) {
            return res.status(500).json({
                message: "Failed to load bookings",
            });
        }
    }

    //Delete Booking
    static async deleteBooking(req, res) {
        try {
            const id = Number(req.params.id);

            if(Number.isNaN(id)){
                return res.status(400).json({
                    message: "Invalid booking ID",
                });
            }

            await BookingModel.delete(id);

            return res.status(200).json({
                message: "booking cancelled successfully",
            });
        } catch (error) {
            console.log(error);
            return res.status(500).json({
                message: "Failed to cancel booking",
            });
        }
    }

    static async getMemberBookingsXML(req, res) {
        try{
            const date = new Date().toLocaleDateString("en-AU", {
    timeZone: "Australia/Brisbane",
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
}).split("/").reverse().join("-");
            const bookings = await BookingModel.getByMemberId(req.authenticatedUser.id);

const sessions = await SessionActivityModel.getAll();

const enrichedBookings = bookings.map((booking) => {
    const session = sessions.find(
        (s) => Number(s.session.id) === Number(booking.sessionId)
    );

    return {
        ...booking,
        session: session || null,
    };
});

        return res
            .status(200)
            .contentType("text/xml")
            .render("xml/member_bookings.xml.ejs", {
                bookings: enrichedBookings,
                date,
                member: req.authenticatedUser,
            });
        } catch (error) {
            console.error(error);
            return res.status(500).json({
                message: "Failed to export bookings",
            });
        }
    }
}

